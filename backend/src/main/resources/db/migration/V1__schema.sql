-- Esquema de Hucha. SQL compatible con PostgreSQL y con H2 en modo PostgreSQL.

CREATE TABLE users (
    id                    UUID PRIMARY KEY,
    email                 VARCHAR(160) NOT NULL UNIQUE,
    full_name             VARCHAR(120) NOT NULL,
    password_hash         VARCHAR(100) NOT NULL,
    role                  VARCHAR(20)  NOT NULL,
    status                VARCHAR(20)  NOT NULL,
    failed_login_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE refresh_tokens (
    id           UUID PRIMARY KEY,
    user_id      UUID         NOT NULL REFERENCES users (id),
    family_id    UUID         NOT NULL,
    token_hash   VARCHAR(64)  NOT NULL UNIQUE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at   TIMESTAMP WITH TIME ZONE,
    replaced_by  UUID,
    user_agent   VARCHAR(255),
    ip_address   VARCHAR(64)
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);

CREATE TABLE accounts (
    id          UUID PRIMARY KEY,
    iban        VARCHAR(34)    NOT NULL UNIQUE,
    owner_id    UUID REFERENCES users (id),
    type        VARCHAR(20)    NOT NULL,
    name        VARCHAR(60)    NOT NULL,
    status      VARCHAR(20)    NOT NULL,
    balance     NUMERIC(19, 2) NOT NULL,
    currency    VARCHAR(3)     NOT NULL,
    daily_limit NUMERIC(19, 2),
    goal_amount NUMERIC(19, 2),
    icon        VARCHAR(30),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT chk_accounts_customer_balance CHECK (type = 'SYSTEM' OR balance >= 0)
);
CREATE INDEX idx_accounts_owner ON accounts (owner_id);

-- Libro mayor de doble entrada: cada asiento tiene al menos dos apuntes y suman cero.
CREATE TABLE journal_entries (
    id           UUID PRIMARY KEY,
    type         VARCHAR(30)  NOT NULL,
    description  VARCHAR(200) NOT NULL,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    reference_id UUID
);

CREATE TABLE postings (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id          UUID           NOT NULL REFERENCES journal_entries (id),
    account_id        UUID           NOT NULL REFERENCES accounts (id),
    entry_type        VARCHAR(30)    NOT NULL,
    amount            NUMERIC(19, 2) NOT NULL,
    balance_after     NUMERIC(19, 2) NOT NULL,
    category          VARCHAR(30),
    counterparty_name VARCHAR(120),
    counterparty_iban VARCHAR(34),
    concept           VARCHAR(140),
    occurred_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_postings_amount_not_zero CHECK (amount <> 0)
);
CREATE INDEX idx_postings_account_time ON postings (account_id, occurred_at);
CREATE INDEX idx_postings_entry ON postings (entry_id);

CREATE TABLE payees (
    id         UUID PRIMARY KEY,
    owner_id   UUID         NOT NULL REFERENCES users (id),
    name       VARCHAR(120) NOT NULL,
    iban       VARCHAR(34)  NOT NULL,
    alias      VARCHAR(60),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_payees_owner_iban UNIQUE (owner_id, iban)
);

CREATE TABLE transfers (
    id               UUID PRIMARY KEY,
    created_by       UUID           NOT NULL REFERENCES users (id),
    from_account_id  UUID           NOT NULL REFERENCES accounts (id),
    to_account_id    UUID REFERENCES accounts (id),
    to_iban          VARCHAR(34)    NOT NULL,
    beneficiary_name VARCHAR(120)   NOT NULL,
    amount           NUMERIC(19, 2) NOT NULL,
    concept          VARCHAR(140),
    status           VARCHAR(20)    NOT NULL,
    sca_required     BOOLEAN        NOT NULL,
    sca_code_hash    VARCHAR(64),
    sca_attempts     INTEGER        NOT NULL DEFAULT 0,
    sca_expires_at   TIMESTAMP WITH TIME ZONE,
    idempotency_key  VARCHAR(80)    NOT NULL,
    request_hash     VARCHAR(64)    NOT NULL,
    rejection_reason VARCHAR(60),
    journal_entry_id UUID REFERENCES journal_entries (id),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_transfers_idempotency UNIQUE (created_by, idempotency_key)
);
CREATE INDEX idx_transfers_from_account ON transfers (from_account_id, created_at);

CREATE TABLE cards (
    id             UUID PRIMARY KEY,
    account_id     UUID           NOT NULL REFERENCES accounts (id),
    owner_id       UUID           NOT NULL REFERENCES users (id),
    holder_name    VARCHAR(120)   NOT NULL,
    last4          VARCHAR(4)     NOT NULL,
    expiry_month   INTEGER        NOT NULL,
    expiry_year    INTEGER        NOT NULL,
    status         VARCHAR(20)    NOT NULL,
    online_enabled BOOLEAN        NOT NULL,
    monthly_limit  NUMERIC(19, 2) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_cards_owner ON cards (owner_id);

CREATE TABLE card_transactions (
    id               UUID PRIMARY KEY,
    card_id          UUID           NOT NULL REFERENCES cards (id),
    merchant         VARCHAR(120)   NOT NULL,
    category         VARCHAR(30)    NOT NULL,
    amount           NUMERIC(19, 2) NOT NULL,
    online           BOOLEAN        NOT NULL,
    status           VARCHAR(20)    NOT NULL,
    decline_reason   VARCHAR(40),
    journal_entry_id UUID REFERENCES journal_entries (id),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_card_transactions_card ON card_transactions (card_id, created_at);

CREATE TABLE notifications (
    id         UUID PRIMARY KEY,
    user_id    UUID         NOT NULL REFERENCES users (id),
    type       VARCHAR(40)  NOT NULL,
    title      VARCHAR(120) NOT NULL,
    body       VARCHAR(500) NOT NULL,
    read_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_notifications_user ON notifications (user_id, created_at);

-- Outbox transaccional: los eventos se guardan en la misma transacción que el cambio
-- y un proceso aparte los publica, así nunca se pierde ni se inventa un evento.
CREATE TABLE outbox_events (
    id           UUID PRIMARY KEY,
    event_type   VARCHAR(60)   NOT NULL,
    aggregate_id UUID          NOT NULL,
    payload      VARCHAR(4000) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    attempts     INTEGER       NOT NULL DEFAULT 0,
    last_error   VARCHAR(500)
);
CREATE INDEX idx_outbox_pending ON outbox_events (published_at, created_at);

CREATE TABLE audit_events (
    id          UUID PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id    UUID,
    actor_email VARCHAR(160),
    action      VARCHAR(40)   NOT NULL,
    target_type VARCHAR(30),
    target_id   VARCHAR(64),
    ip_address  VARCHAR(64),
    details     VARCHAR(1000)
);
CREATE INDEX idx_audit_time ON audit_events (occurred_at);
CREATE INDEX idx_audit_action ON audit_events (action);
